function jokeForDate(d) {
  var start = new Date(d.getFullYear(), 0, 0);
  var dayOfYear = Math.floor((d - start) / 86400000);
  var seed = d.getFullYear() * 366 + dayOfYear;
  return jokes[seed % jokes.length];
}
