function jokeIndexForLocalDate(year, month, day, count) {
  var days = Math.floor(Date.UTC(year, month - 1, day) / 86400000);
  var origin = Math.floor(Date.UTC(2020, 0, 1) / 86400000);
  var n = days - origin;
  if (!count || count < 1) return 0;
  return ((n % count) + count) % count;
}
